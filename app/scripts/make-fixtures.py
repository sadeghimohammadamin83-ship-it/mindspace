"""Generates the SYNTHETIC document fixtures (deterministic text, no real user files).
Run: python3 scripts/make-fixtures.py   (needs reportlab + Pillow; output is committed)"""
import json, os
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.lib import pdfencrypt
from PIL import Image, ImageDraw, ImageFont

OUT = os.path.join(os.path.dirname(__file__), '..', 'tests', 'fixtures', 'documents')
os.makedirs(OUT, exist_ok=True)
FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
pdfmetrics.registerFont(TTFont('DV', FONT))

import re
def vis(s):
    # Real PDFs store RTL text in visual order (pdf.js reverses it back to logical), so mimic that.
    return re.sub(r'[^\x00-\x7f]+(?: [^\x00-\x7f]+)*', lambda m: m.group(0)[::-1], s)

def pdf(name, pages, **kw):
    c = canvas.Canvas(os.path.join(OUT, name), pagesize=A4, invariant=1, **kw)
    c.setTitle(name)
    for lines in pages:
        c.setFont('DV', 12)
        y = 800
        for ln in lines:
            c.drawString(60, y, vis(ln))
            y -= 22
        c.showPage()
    c.save()

